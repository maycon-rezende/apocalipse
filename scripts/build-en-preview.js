function write(relativePath, contents) {
  const destination = path.join(OUTPUT, relativePath);
  fs.mkdirSync(path.dirname(destination), { recursive: true });
  fs.writeFileSync(destination, contents.replace(/\r\n/g, '\n'), 'utf8');
}

function build() {
  const dictionary = loadDictionary('en');
  fs.mkdirSync(OUTPUT, { recursive: true });
  READY_PAGES.forEach(function (page) {
    write(page, preparePage(page, dictionary));
  });
  fs.rmSync(path.join(OUTPUT, 'pending.html'), { force: true });
  write('README.md', `# International edition preview\n\nThis directory is generated by \`node scripts/build-en-preview.js\`.\n\nDo not edit the HTML files here manually. Edit the root pages and the modular i18n catalogs, then run the generator again. All public sectors are generated in English and share the project assets and state with the Brazilian edition.\n`);
  console.log(`English preview generated: ${Array.from(READY_PAGES).join(', ')}`);
}

build();
